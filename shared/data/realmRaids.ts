export function getDailyRaidTheme(epochDay?: number): { theme: RealmRaidTheme; dayIndex: number; dateStr: string } {
  const day = epochDay ?? Math.floor(Date.now() / (24 * 60 * 60 * 1000));
  const idx = Math.abs(day) % RAID_THEMES.length;
  const dateStr = new Date(day * 24 * 60 * 60 * 1000).toISOString().split("T")[0]!;
  return {
    theme: RAID_THEMES[idx]!,
    dayIndex: idx,
    dateStr,
  };
}
